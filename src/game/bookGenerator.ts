let bookCounter = 100;

export function generateRandomBook(forceGenre?: BookGenre, forceRarity?: BookRarity): BookItem {
  bookCounter++;
  const template = forceGenre
    ? BOOK_TITLES_POOL.find((b) => b.genre === forceGenre) || BOOK_TITLES_POOL[Math.floor(Math.random() * BOOK_TITLES_POOL.length)]
    : BOOK_TITLES_POOL[Math.floor(Math.random() * BOOK_TITLES_POOL.length)];

  const rarities: BookRarity[] = ['common', 'common', 'uncommon', 'uncommon', 'rare', 'vintage'];
  const rarity = forceRarity || rarities[Math.floor(Math.random() * rarities.length)];

  const conditions: BookCondition[] = ['pristine', 'well_loved', 'well_loved', 'tattered', 'needs_restoration'];
  const condition = rarity === 'vintage' ? 'needs_restoration' : conditions[Math.floor(Math.random() * conditions.length)];

  const genreConf = GENRE_COLORS[template.genre];
  const year = 1800 + Math.floor(Math.random() * 120);

  const value = rarity === 'mythic' ? 500 : rarity === 'vintage' ? 250 : rarity === 'rare' ? 120 : rarity === 'uncommon' ? 60 : 30;

  return {
    id: `book_${bookCounter}_${Date.now() % 10000}`,
    title: template.title,
    author: template.author,
    year,
    genre: template.genre,
    rarity,
    deweyDecimal: template.dewey,
    condition,
    spineColor: genreConf.spine,
    accentColor: genreConf.text,
    lore: `A cherished volume cataloged under Dewey ${template.dewey}. Stamped with the library seal.`,
    restored: condition === 'pristine' || condition === 'well_loved',
    value,
  };
}

